"""ReArch API.

Repos are owned by a visitor and one visitor can never read another's
analyses. A shared read-only "demo" account holds pre-analyzed example repos
that everyone can open. Identity is the `X-User` header: locally any name,
and in public mode (REARCH_PUBLIC_MODE=1) a long random id generated by the
browser, treated as a bearer secret (see api/security.py). get_current_user()
is the single swap point for real authentication later.

Run locally with:
    .venv/Scripts/uvicorn api.main:app --reload --port 8000
"""
import hashlib
import hmac
import json
import logging
import os
import shutil
import threading
from contextlib import asynccontextmanager
from pathlib import Path

from dotenv import load_dotenv
from fastapi import BackgroundTasks, Depends, FastAPI, Header, HTTPException, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import PlainTextResponse, RedirectResponse
from pydantic import BaseModel

from api.security import (
    DEMO_USER, analysis_slot, enforce_analysis_limits, public_mode, release_slot, try_acquire_slot,
    validate_git_url, validate_identity,
)
from api.services.graph_store import GraphStore
from api.services.user_store import UserStore
from parser.pipeline.diff_graphs import diff_graphs
from parser.pipeline.ingest_repo import main as ingest_repo_main
from parser.pipeline.migration_plan import render_markdown

load_dotenv()
log = logging.getLogger("rearch")

PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_ROOT = Path(os.environ.get("REARCH_DATA_DIR") or PROJECT_ROOT / "api" / "data")
REPOS_ROOT = DATA_ROOT / "repos"
USER_DB_PATH = DATA_ROOT / "users.sqlite3"
DEMO_ROOT = PROJECT_ROOT / "demo"

_user_store: UserStore | None = None
_graph_stores: dict[str, GraphStore] = {}
_graph_stores_lock = threading.Lock()
# Each open Kùzu database holds its own buffer pool, so on a small host the number kept open is bounded
# (least recently used are closed and reopen on demand). 0 keeps every store open, the old behaviour.
MAX_OPEN_GRAPHS = int(os.environ.get("REARCH_MAX_OPEN_GRAPHS", "0"))


def get_user_store() -> UserStore:
    global _user_store
    if _user_store is None:
        _user_store = UserStore(str(USER_DB_PATH))
    return _user_store


def get_graph_store(repo_id: str) -> GraphStore:
    with _graph_stores_lock:
        store = _graph_stores.pop(repo_id, None)
        if store is None:
            store = GraphStore(str(REPOS_ROOT / repo_id / "kuzu_db"))
        _graph_stores[repo_id] = store  # re-inserted last: dict order is recency order
        if MAX_OPEN_GRAPHS:
            # The requested store counts as open: it is about to be used, and a closed one reopens on use.
            open_ids = [rid for rid, st in _graph_stores.items() if st.is_open or st is store]
            for rid in open_ids[:-MAX_OPEN_GRAPHS]:
                _graph_stores[rid].close()
        return store


def reset_graph_store(repo_id: str) -> GraphStore:
    """Wipe and recreate the Kuzu DB for a repo. Required before re-analysis:
    Kuzu's MERGE only adds/updates, so without a full reset, nodes/edges
    removed since the last analysis would linger as stale data forever."""
    with _graph_stores_lock:
        existing = _graph_stores.pop(repo_id, None)
    if existing is not None:
        existing.close()
    db_path = REPOS_ROOT / repo_id / "kuzu_db"
    for path in (db_path, db_path.with_name(db_path.name + ".wal")):
        if path.is_dir():
            shutil.rmtree(path)
        elif path.exists():
            path.unlink()
    return get_graph_store(repo_id)


def demo_user_id() -> str:
    return get_user_store().get_or_create_user(DEMO_USER)


def seed_demo_repos() -> None:
    """Load the pre-analyzed example repos bundled in demo/ (graph, narratives
    and migration plan computed ahead of time), so a fresh server — including
    one with an ephemeral disk — shows real results instantly, with no cloning
    and no LLM calls at startup."""
    if not DEMO_ROOT.is_dir():
        return
    store = get_user_store()
    owner = demo_user_id()
    have = {repo["git_url"] for repo in store.list_repos(owner)}
    for folder in sorted(p for p in DEMO_ROOT.iterdir() if (p / "meta.json").is_file()):
        meta = json.loads((folder / "meta.json").read_text(encoding="utf-8"))
        if meta["git_url"] in have:
            continue
        repo_id = store.create_repo(owner, meta["name"], meta["git_url"])
        target = REPOS_ROOT / repo_id
        target.mkdir(parents=True, exist_ok=True)
        for name in ("graph.json", "narratives.json", "migration.json"):
            if (folder / name).is_file():
                shutil.copyfile(folder / name, target / name)
        get_graph_store(repo_id).load_graph_json(str(target / "graph.json"))
        store.set_repo_status(repo_id, "ready")
        log.info("seeded demo repo %s", meta["name"])


def should_seed_demo() -> bool:
    """Examples are seeded in public mode so a fresh server shows results at once. A deployment whose UI
    already serves the examples as static files turns it off (REARCH_SEED_DEMO=0): seeding costs the
    server its startup time, which on a small free host is most of a cold start."""
    explicit = os.environ.get("REARCH_SEED_DEMO")
    if explicit is not None:
        return explicit == "1"
    return public_mode()


@asynccontextmanager
async def lifespan(_: FastAPI):
    get_user_store().fail_interrupted()
    if should_seed_demo():
        seed_demo_repos()
    yield


app = FastAPI(title="ReArch API", lifespan=lifespan)
app.add_middleware(
    CORSMiddleware,
    allow_origins=[o.strip() for o in os.environ.get("REARCH_CORS_ORIGINS", "http://localhost:5173").split(",") if o.strip()],
    allow_methods=["GET", "POST"],
    allow_headers=["*"],
)


def get_current_user(x_user: str = Header(...)) -> str:
    username = x_user.strip()
    if not username:
        raise HTTPException(400, "X-User header must be a non-empty username")
    validate_identity(username)
    return get_user_store().get_or_create_user(username)


def require_repo(repo_id: str, user_id: str, *, write: bool = False) -> dict:
    """Load a repo the caller may use. Anyone can READ a demo repo; only the
    owner can write, and demo repos are never writable."""
    repo = get_user_store().get_repo(repo_id)
    if repo is None:
        raise HTTPException(404, "no such repo")
    is_demo = repo["user_id"] == demo_user_id()
    if write:
        if is_demo:
            raise HTTPException(403, "The demo repositories are read-only.")
        if repo["user_id"] != user_id:
            raise HTTPException(404, "no such repo")
    elif repo["user_id"] != user_id and not is_demo:
        raise HTTPException(404, "no such repo")
    return repo


def run_reanalysis(repo_id: str, git_url: str, *, fresh_db: bool) -> None:
    """Shared by the manual reanalyze endpoint, initial repo creation, and
    the git webhook — one place that runs the pipeline and updates status,
    so all three trigger paths behave identically."""
    store = get_user_store()
    work_dir = REPOS_ROOT / repo_id
    store.set_repo_status(repo_id, "pending")
    try:
        result = ingest_repo_main(git_url, str(work_dir))
        store_fn = reset_graph_store if fresh_db else get_graph_store
        store_fn(repo_id).load_graph_json(str(result["graph_path"]))
        store.set_repo_status(repo_id, "ready")
    except Exception as exc:
        log.exception("analysis failed for repo %s", repo_id)
        # RuntimeErrors are our own curated messages ("repository too large");
        # anything else may contain server paths, so public mode hides it.
        shown = str(exc) if isinstance(exc, RuntimeError) or not public_mode() else "Analysis failed unexpectedly. Try another repository."
        store.set_repo_status(repo_id, "error", shown)


def normalize_git_url(url: str) -> str:
    """Strip protocol/trailing-slash/.git so URLs from different sources
    (our stored git_url vs. GitHub's webhook payload fields) compare equal."""
    url = url.strip().lower()
    for prefix in ("https://", "http://", "git@github.com:"):
        if url.startswith(prefix):
            url = url[len(prefix):]
    return url.rstrip("/").removesuffix(".git")


class CreateRepoRequest(BaseModel):
    git_url: str
    name: str | None = None


@app.get("/", include_in_schema=False)
def root():
    """Anyone opening the API's own URL is sent to the web UI when one is configured."""
    ui_url = os.environ.get("REARCH_UI_URL")
    return RedirectResponse(ui_url) if ui_url else {"service": "ReArch API", "docs": "/docs"}


@app.get("/api/health")
def health():
    return {"status": "ok", "public_mode": public_mode()}


@app.get("/api/demo/repos")
def list_demo_repos():
    """The shared example repos. No identity needed: this is what a first-time
    visitor sees before analyzing anything of their own."""
    repos = get_user_store().list_repos(demo_user_id())
    return [{**repo, "demo": True} for repo in repos]


def analysis_job(repo_id: str, git_url: str, fresh_db: bool) -> None:
    try:
        run_reanalysis(repo_id, git_url, fresh_db=fresh_db)
    finally:
        release_slot()


def claim_analysis(user_id: str, request: Request) -> None:
    """Reserve the one analysis slot and charge the visitor's rate limit, or
    raise. Whoever claims it MUST hand it to a job that releases it."""
    if not try_acquire_slot():
        raise HTTPException(503, "Another analysis is running on this small server. Try again in a minute.")
    try:
        enforce_analysis_limits(user_id, request)
    except BaseException:
        release_slot()
        raise


@app.post("/api/repos")
def create_repo(body: CreateRepoRequest, request: Request, background: BackgroundTasks, user_id: str = Depends(get_current_user)):
    """Starts an analysis and returns at once with status "pending": it takes
    minutes, longer than hosting proxies allow one request to live, so the UI
    polls GET /api/repos for the result."""
    if user_id == demo_user_id():
        raise HTTPException(403, "The demo account is read-only.")
    git_url = validate_git_url(body.git_url)
    store = get_user_store()
    name = (body.name or git_url.rstrip("/").rsplit("/", 1)[-1].removesuffix(".git")).strip()[:80] or "repo"
    claim_analysis(user_id, request)
    try:
        repo_id = store.create_repo(user_id, name, git_url)
    except BaseException:
        release_slot()
        raise
    background.add_task(analysis_job, repo_id, git_url, False)
    return store.get_repo(repo_id)


@app.post("/api/repos/{repo_id}/reanalyze")
def reanalyze_repo(repo_id: str, request: Request, background: BackgroundTasks, user_id: str = Depends(get_current_user)):
    repo = require_repo(repo_id, user_id, write=True)
    validate_git_url(repo["git_url"])
    claim_analysis(user_id, request)
    get_user_store().set_repo_status(repo_id, "pending")
    background.add_task(analysis_job, repo_id, repo["git_url"], True)
    return get_user_store().get_repo(repo_id)


def reanalyze_all(targets: list[tuple[str, str]]) -> None:
    with analysis_slot(wait=True):
        for repo_id, git_url in targets:
            run_reanalysis(repo_id, git_url, fresh_db=True)


@app.post("/api/webhooks/github", status_code=202)
async def github_webhook(request: Request, background: BackgroundTasks):
    """Push-triggered re-analysis. Requires WEBHOOK_SECRET (GitHub repo
    settings -> Webhooks -> Secret) and verifies the request really came from
    GitHub via HMAC-SHA256 over the raw body. The analysis runs in the
    background: it takes minutes, and GitHub abandons a delivery after ~10s.
    """
    secret = os.environ.get("WEBHOOK_SECRET")
    if not secret:
        raise HTTPException(501, "WEBHOOK_SECRET not configured; webhook disabled")

    body = await request.body()
    signature = request.headers.get("X-Hub-Signature-256", "")
    expected = "sha256=" + hmac.new(secret.encode(), body, hashlib.sha256).hexdigest()
    if not hmac.compare_digest(signature, expected):
        raise HTTPException(401, "invalid webhook signature")

    payload = json.loads(body)
    if request.headers.get("X-GitHub-Event") != "push":
        return {"status": "ignored", "reason": "not a push event"}

    repo_info = payload.get("repository", {})
    pushed = normalize_git_url(repo_info.get("clone_url") or repo_info.get("html_url", ""))

    demo_id = demo_user_id()
    targets = [
        (repo["id"], repo["git_url"])
        for repo in get_user_store().all_repos()
        if repo["user_id"] != demo_id and normalize_git_url(repo["git_url"]) == pushed
    ]
    if targets:
        background.add_task(reanalyze_all, targets)
    return {"status": "accepted", "matched_repos": [repo_id for repo_id, _ in targets]}


