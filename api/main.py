@app.get("/api/repos/{repo_id}/graph")
def get_repo_graph(repo_id: str, user_id: str = Depends(get_current_user)):
    repo = require_repo(repo_id, user_id)
    if repo["status"] != "ready":
        raise HTTPException(409, f"repo status is '{repo['status']}', not ready")
    graph_store = get_graph_store(repo_id)
    return {"nodes": graph_store.all_nodes(), "edges": graph_store.all_edges()}


def read_json_file(repo_id: str, name: str, default):
    path = REPOS_ROOT / repo_id / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


@app.get("/api/repos/{repo_id}/narratives")
def get_repo_narratives(repo_id: str, user_id: str = Depends(get_current_user)):
    require_repo(repo_id, user_id)
    return read_json_file(repo_id, "narratives.json", {})


def load_migration_plan(repo_id: str) -> dict:
    plan = read_json_file(repo_id, "migration.json", None)
    if plan is None:
        raise HTTPException(404, "no migration plan yet; re-analyze this repo to generate one")
    return plan


@app.get("/api/repos/{repo_id}/migration")
def get_repo_migration(repo_id: str, user_id: str = Depends(get_current_user)):
    require_repo(repo_id, user_id)
    return load_migration_plan(repo_id)


@app.get("/api/repos/{repo_id}/migration.md", response_class=PlainTextResponse)
def get_repo_migration_markdown(repo_id: str, user_id: str = Depends(get_current_user)):
    repo = require_repo(repo_id, user_id)
    return render_markdown(load_migration_plan(repo_id), repo["name"])


@app.get("/api/repos/{repo_id}/commits")
def list_repo_commits(repo_id: str, user_id: str = Depends(get_current_user)):
    require_repo(repo_id, user_id)
    snapshots_dir = REPOS_ROOT / repo_id / "snapshots"
    if not snapshots_dir.exists():
        return []
    commits = [{"commit_sha": f.stem, "analyzed_at": f.stat().st_mtime} for f in snapshots_dir.glob("*.json")]
    commits.sort(key=lambda c: c["analyzed_at"], reverse=True)
    return commits


@app.get("/api/repos/{repo_id}/diff")
def get_repo_diff(repo_id: str, from_commit: str, to_commit: str, user_id: str = Depends(get_current_user)):
    require_repo(repo_id, user_id)
    snapshots_dir = REPOS_ROOT / repo_id / "snapshots"
    # Commit ids come from the URL; accept only hex so they can't escape the snapshots dir.
    if not all(c.isalnum() for c in from_commit + to_commit):
        raise HTTPException(400, "invalid commit id")
    old_path = snapshots_dir / f"{from_commit}.json"
    new_path = snapshots_dir / f"{to_commit}.json"
    if not old_path.exists() or not new_path.exists():
        raise HTTPException(404, "one or both commit snapshots not found for this repo")
    return diff_graphs(
        json.loads(old_path.read_text(encoding="utf-8")),
        json.loads(new_path.read_text(encoding="utf-8")),
    )
